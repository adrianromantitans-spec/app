// UI copy only: never pass group names, member names, titles or messages written by users.
export const nativeCatalog={...translations,...nativeCopy,...featureCopy,...nativeCopyExtra};
const sources=new Map();
for(const [key,entry] of Object.entries(nativeCatalog))for(const value of Object.values(entry))if(typeof value==='string'&&!sources.has(value))sources.set(value,key);
export function nativeText(text,language='es'){
 if(typeof text!=='string')return text;
 const key=Object.hasOwn(nativeCatalog,text)?text:sources.get(text);
 if(!key)return text;
 return language==='es'?key:nativeCatalog[key]?.[language]??key;
}
export function nativeTemplate(language,strings,...values){
 const key=strings.map((part,i)=>part+(i<values.length?`{${i}}`:'')).join('');
 return nativeText(key,language).replace(/\{(\d+)\}/g,(_,i)=>String(values[Number(i)]));
}
