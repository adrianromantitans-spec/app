from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 c=b.new_context(locale='en-GB',viewport={'width':390,'height':844})
 c.route('**/config.js',lambda r:r.fulfill(content_type='application/javascript',body='export const cloudConfig={};'))
 page=c.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:3000/')
 page.get_by_role('button',name='Explore a demo',exact=False).click()
 assert '€' in page.locator('body').inner_text()
 page.get_by_role('button',name='Create group',exact=True).first.click()
 form=page.locator('#group-form')
 form.get_by_label('Group name',exact=True).fill('Lei cu prietenii')
 form.get_by_label('Group currency',exact=False).select_option('RON')
 expect(form.get_by_label('Total group budget (RON)',exact=True)).to_be_visible()
 form.get_by_label('Total group budget (RON)',exact=True).fill('500')
 form.get_by_label("Who's joining?",exact=False).fill('Mihai')
 form.get_by_role('button',name='Create group',exact=True).click()
 expect(page.get_by_role('heading',name='Lei cu prietenii')).to_be_visible()
 assert 'RON' in page.locator('body').inner_text()
 page.get_by_role('button',name='Add expense',exact=True).first.click()
 form=page.locator('#expense-form')
 form.get_by_label('What did you pay for?',exact=True).fill('Bon în lei')
 form.get_by_label('Amount (RON)',exact=True).fill('10.01')
 form.get_by_role('button',name='Save expense',exact=True).click()
 expect(page.get_by_text('Bon în lei',exact=True)).to_be_visible()
 page.get_by_role('button',name='Edit group details').click()
 expect(page.get_by_label('Group currency',exact=False)).to_be_disabled()
 page.keyboard.press('Escape')
 page.reload();page.get_by_role('button',name='Explore a demo',exact=False).click()
 state=page.evaluate("JSON.parse(localStorage.getItem('nexo-local-v1'))")
 group=next(g for g in state['groups'] if g['name']=='Lei cu prietenii')
 assert group['currency']=='RON' and group['expenses'][0]['amount']==1001
 page.get_by_role('button',name='Groups',exact=False).first.click()
 card=page.locator('.group-card').filter(has=page.get_by_role('heading',name='Lei cu prietenii'))
 assert 'RON' in card.inner_text() and '€' not in card.inner_text()
 assert '€' in page.locator('.group-cards').inner_text()
 saved=c.storage_state();romanian=b.new_context(locale='ro-RO',storage_state=saved)
 romanian.route('**/config.js',lambda r:r.fulfill(content_type='application/javascript',body='export const cloudConfig={};'))
 rp=romanian.new_page();rp.goto('http://127.0.0.1:3000/')
 rp.get_by_role('button',name='Explorează un demo',exact=False).click()
 assert 'RON' in rp.locator('body').inner_text()
 assert rp.evaluate("JSON.parse(localStorage.getItem('nexo-local-v1'))")==state
 assert not errors,errors
 print('PASS: EUR and RON remain separate, RON survives reload and language change, currency locks after expenses')
 b.close()
